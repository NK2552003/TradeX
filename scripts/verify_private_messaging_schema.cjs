// Run with @electric-sql/pglite installed locally or exposed through NODE_PATH.
const {PGlite} = require('@electric-sql/pglite');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema storage;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
    grant usage on schema auth to authenticated;
    create table profiles(id uuid primary key);
    create table notifications(id uuid primary key default gen_random_uuid(), user_id uuid not null, actor_id uuid,
      type text, category text not null, title text not null, body text, data jsonb, read_at timestamptz);
    create table chat_threads(id uuid primary key, last_message_preview text, last_message_at timestamptz, updated_at timestamptz);
    create table chat_participants(thread_id uuid, user_id uuid);
    create table chat_messages(id uuid primary key default gen_random_uuid(), thread_id uuid, sender_id uuid, body text, created_at timestamptz default now());
    create table messages(content text);
    create table ai_messages(body text);
    create table copilot_workspaces(state jsonb);
    create table chat_attachments(id uuid);
    create table chat_shared_refs(id uuid);
    create table storage.buckets(id text, allowed_mime_types text[]);
    insert into profiles values ('00000000-0000-0000-0000-000000000001'), ('00000000-0000-0000-0000-000000000002');
  `);
  const migration = fs.readFileSync(path.join(__dirname, '../supabase/migrations/20261115014637_private_messaging_and_web_push.sql'), 'utf8');
  await db.exec(migration);
  const owner = '00000000-0000-0000-0000-000000000001';
  const peer = '00000000-0000-0000-0000-000000000002';
  await db.exec(`set role authenticated; set test.uid = '${owner}';`);
  await db.query('insert into message_identities(user_id,public_key,signing_key,salt,backup) values ($1,$2,$2,$3,$4)', [owner, 'A'.repeat(44), 'salt', {n:'n',c:'ciphertext',t:'tag'}]);
  await assert.rejects(db.query('insert into message_identities(user_id,public_key,signing_key,salt,backup) values ($1,$2,$2,$3,$4)', [peer, 'A'.repeat(44), 'salt', {}]));
  await assert.rejects(db.query('update message_identities set public_key = $1', ['B'.repeat(44)]));
  await db.query('insert into push_subscriptions(user_id,endpoint,p256dh,auth) values ($1,$2,$3,$4)', [owner,'https://fcm.googleapis.com/send/test','key','auth']);
  await db.exec(`set test.uid = '${peer}';`);
  assert.equal((await db.query('select * from message_identities')).rows.length, 0);
  assert.equal((await db.query('select * from message_public_keys')).rows.length, 1);
  assert.equal((await db.query('select * from push_subscriptions')).rows.length, 0);
  await assert.rejects(db.query('select * from push_deliveries'));
  await assert.rejects(db.query('select * from claim_push_deliveries()'));
  await db.exec('reset role;');
  await assert.rejects(db.query("insert into messages values ('plaintext')"));
  await assert.rejects(db.query("insert into ai_messages values ('plaintext')"));
  await assert.rejects(db.query(`insert into copilot_workspaces values ('{"threads": []}')`));
  await db.query(`insert into copilot_workspaces values ('{"encrypted":"e2ee:v1:ciphertext"}')`);
  await db.query('insert into chat_threads(id) values ($1)', [owner]);
  await db.query('insert into chat_participants values ($1,$2),($1,$1)', [owner,peer]);
  await db.query("insert into chat_messages(thread_id,sender_id,body) values ($1,$2,'e2ee:v1:secret')", [owner,peer]);
  const notifications = (await db.query('select * from notifications')).rows;
  assert.equal(notifications.length, 1);
  assert.equal(notifications[0].category, 'message');
  assert(!JSON.stringify(notifications).includes('secret'));
  assert.equal((await db.query('select * from push_deliveries')).rows.length, 1);
  await db.exec('set role service_role;');
  assert.equal((await db.query('select * from claim_push_deliveries()')).rows.length, 1);
  assert.equal((await db.query('select * from claim_push_deliveries()')).rows.length, 0);
  await db.close();
  console.log('Schema, identity ownership, immutable keys, queue leases and plaintext rejection passed.');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
