#!/usr/bin/env python3
"""Export public Flutter configuration without bundling server/API secrets."""
from pathlib import Path
import os

ROOT = Path(__file__).resolve().parent.parent
PUBLIC_KEYS = {
    'SUPABASE_URL', 'SUPABASE_ANON_KEY', 'SUPABASE_PUBLISHABLE_KEY',
    'REVENUECAT_TEST_API_KEY', 'REVENUECAT_ANDROID_API_KEY',
    'REVENUECAT_IOS_API_KEY', 'RAZORPAY_TEST_KEY_ID', 'ENVIRONMENT',
    'COPILOT_API_URL', 'APP_UPDATE_MANIFEST_URL',
    'APP_UPDATE_CHECKS_ENABLED',
}


def export_public_settings(source: str, environment=None) -> str:
    values = {}
    def add(key, value):
        normalized = key.removeprefix('NEXT_PUBLIC_').removeprefix('VITE_').removeprefix('REACT_APP_')
        if normalized in PUBLIC_KEYS:
            values[normalized] = value.strip()
    for line in source.splitlines():
        if '=' in line and not line.lstrip().startswith('#'):
            key, value = line.split('=', 1)
            add(key.strip(), value)
    # Hosting environment wins over local files, including prefixed aliases.
    for key, value in (environment or {}).items():
        add(key, value)
    lines = ['# Public application settings. Generated by scripts/prepare_client_config.py.']
    lines.extend(f'{key}={value}' for key, value in sorted(values.items()))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    source = ROOT / '.env'
    if not source.exists():
        source = ROOT / '.env.example'
    destination = ROOT / 'assets/config/client.env'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(export_public_settings(source.read_text() if source.exists() else "", os.environ))
    from generate_app_update_manifest import generate_manifest
    generate_manifest(platforms=('web',))
    print('Public Flutter configuration generated; server secrets excluded.')
